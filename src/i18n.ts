export type MessageKey = keyof typeof en;

/** The interface language this plugin speaks: Chinese or English. */
export function uiLocale(): 'zh' | 'en' {
  return getLanguage().toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

export function t(key: MessageKey, values: Record<string, string | number> = {}) {
  const table = uiLocale() === 'zh' ? zh : en;
  return table[key].replace(/\{(\w+)\}/g, (_all, name: string) =>
    String(values[name] ?? '')
  );
}
